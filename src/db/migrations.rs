#[cfg(test)]
mod tests {
    use super::*;

    #[derive(Default)]
    struct RecordingExecutor {
        statements: Vec<String>,
        marked: Vec<u32>,
        fail_statement: Option<usize>,
    }

    impl MigrationExecutor for RecordingExecutor {
        fn execute_statement(&mut self, statement: &str) -> Result<(), String> {
            let next = self.statements.len();
            if self.fail_statement == Some(next) {
                return Err("forced statement failure".to_owned());
            }
            self.statements.push(statement.to_owned());
            Ok(())
        }

        fn mark_applied(&mut self, migration: &Migration) -> Result<(), String> {
            self.marked.push(migration.version);
            Ok(())
        }
    }

    #[test]
    fn migrations_are_valid() {
        validate(all()).unwrap();
    }

    #[test]
    fn render_includes_core_tables_and_markers() {
        let rendered = render_all().unwrap();

        assert!(rendered.contains("DEFINE TABLE IF NOT EXISTS user SCHEMAFULL;"));
        assert!(rendered.contains("DEFINE TABLE IF NOT EXISTS audit_log SCHEMAFULL;"));
        assert!(rendered.contains("DEFINE TABLE IF NOT EXISTS has_role TYPE RELATION"));
        assert!(rendered.contains("UPSERT mythenheim_migration:5"));
    }

    #[test]
    fn runner_marks_migration_after_statements() {
        let mut executor = RecordingExecutor::default();

        run(&all()[..1], &mut executor).unwrap();

        assert_eq!(executor.marked, vec![1]);
        assert_eq!(executor.statements.len(), all()[0].statements.len());
    }

    #[test]
    fn runner_does_not_mark_failed_migration() {
        let mut executor = RecordingExecutor {
            fail_statement: Some(1),
            ..RecordingExecutor::default()
        };

        let err = run(&all()[..1], &mut executor).unwrap_err();

        assert!(err.to_string().contains("forced statement failure"));
        assert!(executor.marked.is_empty());
    }

    #[test]
    fn validation_rejects_non_increasing_versions() {
        let migrations = [
            Migration {
                version: 2,
                name: "second",
                statements: &["SELECT 1;"],
                checksum: "2",
            },
            Migration {
                version: 1,
                name: "first",
                statements: &["SELECT 1;"],
                checksum: "1",
            },
        ];

        assert!(matches!(
            validate(&migrations),
            Err(MigrationValidationError::NonIncreasingVersion { .. })
        ));
    }
}
