use std::{collections::BTreeSet, fmt};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Migration {
    pub version: u32,
    pub name: &'static str,
    pub statements: &'static [&'static str],
    pub checksum: &'static str,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MigrationValidationError {
    EmptySet,
    InvalidName { version: u32, name: String },
    EmptyStatement { version: u32 },
    NonIncreasingVersion { previous: u32, current: u32 },
    DuplicateVersion(u32),
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum MigrationRunError {
    Validation(MigrationValidationError),
    Statement {
        version: u32,
        name: &'static str,
        statement_index: usize,
        source: String,
    },
    MarkApplied {
        version: u32,
        name: &'static str,
        source: String,
    },
}

pub trait MigrationExecutor {
    fn execute_statement(&mut self, statement: &str) -> Result<(), String>;
    fn mark_applied(&mut self, migration: &Migration) -> Result<(), String>;
}

pub fn all() -> &'static [Migration] {
    MIGRATIONS
}

pub fn validate(migrations: &[Migration]) -> Result<(), MigrationValidationError> {
    if migrations.is_empty() {
        return Err(MigrationValidationError::EmptySet);
    }

    let mut previous = None;
    let mut seen = BTreeSet::new();
    for migration in migrations {
        if let Some(previous) = previous
            && migration.version <= previous
        {
            return Err(MigrationValidationError::NonIncreasingVersion {
                previous,
                current: migration.version,
            });
        }
        previous = Some(migration.version);

        if !seen.insert(migration.version) {
            return Err(MigrationValidationError::DuplicateVersion(
                migration.version,
            ));
        }

        if !valid_name(migration.name) {
            return Err(MigrationValidationError::InvalidName {
                version: migration.version,
                name: migration.name.to_owned(),
            });
        }

        for statement in migration.statements {
            if statement.trim().is_empty() {
                return Err(MigrationValidationError::EmptyStatement {
                    version: migration.version,
                });
            }
        }
    }

    Ok(())
}

pub fn render_all() -> Result<String, MigrationValidationError> {
    validate(MIGRATIONS)?;

    let mut output = String::new();
    output.push_str("-- Mythenheim SurrealDB schema migrations.\n");
    output.push_str("-- Generated by mythenheim --print-migrations.\n\n");
    for migration in MIGRATIONS {
        output.push_str(&format!(
            "-- migration {:04}: {}\n",
            migration.version, migration.name
        ));
        for statement in migration.statements {
            output.push_str(statement.trim());
            output.push_str("\n\n");
        }
        output.push_str(&mark_applied_statement(migration));
        output.push_str("\n\n");
    }

    Ok(output)
}

pub fn run<E: MigrationExecutor>(
    migrations: &[Migration],
    executor: &mut E,
) -> Result<(), MigrationRunError> {
    validate(migrations).map_err(MigrationRunError::Validation)?;

    for migration in migrations {
        for (index, statement) in migration.statements.iter().enumerate() {
            executor.execute_statement(statement).map_err(|source| {
                MigrationRunError::Statement {
                    version: migration.version,
                    name: migration.name,
                    statement_index: index,
                    source,
                }
            })?;
        }
        executor
            .mark_applied(migration)
            .map_err(|source| MigrationRunError::MarkApplied {
                version: migration.version,
                name: migration.name,
                source,
            })?;
    }

    Ok(())
}

pub fn mark_applied_statement(migration: &Migration) -> String {
    format!(
        "UPSERT mythenheim_migration:{} CONTENT {{ version: {}, name: {:?}, checksum: {:?}, applied_at: time::now() }};",
        migration.version, migration.version, migration.name, migration.checksum
    )
}

impl fmt::Display for MigrationValidationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptySet => formatter.write_str("migration set is empty"),
            Self::InvalidName { version, name } => {
                write!(formatter, "migration {version} has invalid name {name:?}")
            }
            Self::EmptyStatement { version } => {
                write!(formatter, "migration {version} has an empty statement")
            }
            Self::NonIncreasingVersion { previous, current } => write!(
                formatter,
                "migration version {current} must be greater than previous version {previous}"
            ),
            Self::DuplicateVersion(version) => {
                write!(
                    formatter,
                    "migration version {version} appears more than once"
                )
            }
        }
    }
}

impl std::error::Error for MigrationValidationError {}

impl fmt::Display for MigrationRunError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Validation(err) => write!(formatter, "migration validation failed: {err}"),
            Self::Statement {
                version,
                name,
                statement_index,
                source,
            } => write!(
                formatter,
                "migration {version} ({name}) statement {statement_index} failed: {source}"
            ),
            Self::MarkApplied {
                version,
                name,
                source,
            } => write!(
                formatter,
                "migration {version} ({name}) could not be marked applied: {source}"
            ),
        }
    }
}

impl std::error::Error for MigrationRunError {}

fn valid_name(name: &str) -> bool {
    !name.is_empty()
        && name.bytes().all(|byte| {
            byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_' || byte == b'-'
        })
}

